#!/usr/bin/env python3
"""Build the per-tool adapters of a Jarvis plugin repo from its sources.

Sources (hand-edited):
  jarvis-build.json                      repo config: plugin dir, marketplace, peers
  <plugin>/jarvis-extension.json         the manifest: id, agents, skills, relies_on_core
  <plugin>/agents-src/<agent>.md         one source per agent (frontmatter plus body)
  <plugin>/agents-src/rules/<rule>.md    must-follow rules, inlined into agents at build
  <plugin>/skills/<skill>/SKILL.md       skills
  <peers_dir>/<id>.json                  vendored manifests of known peer plugins

Outputs (generated, never hand-edit):
  <plugin>/agents/<agent>.md             Claude Code plugin agents
  <plugin>/standalone/<agent>.md         agents to copy into ~/.claude/agents/
  <project_agents_dir>/<agent>.md        optional: the same standalone agents as project agents
  <plugin>/skills/role-*/SKILL.md        role skills for tools without agent files
  <plugin>/skills/extension-catalog/     core only: every known extension
  <plugin>/.claude-plugin/plugin.json    Claude plugin manifest
  <plugin>/.codex-plugin/plugin.json     Codex plugin manifest
  <plugin>/AGENTS.md, <plugin>/CLAUDE.md always-on file, CLAUDE.md imports it
  .claude-plugin/marketplace.json        Claude marketplace
  .agents/plugins/marketplace.json       Codex marketplace

Usage:
  python3 tools/jarvis-build.py            write every output
  python3 tools/jarvis-build.py --check    fail if any output is stale or a check fails (CI)
  python3 tools/jarvis-build.py --fetch    refresh vendored peer manifests from GitHub
  python3 tools/jarvis-build.py --check --base <ref>
                                           also fail if plugin files changed since <ref>
                                           without a version bump (CI passes the push base)

Version gate: Claude Code and Codex cache a plugin by version, and a running
session keeps the folder of the version it started with. A change shipped under
the same version never reaches new sessions, so every plugin change needs a new
version. A plain build bumps the patch version when plugin files differ from the
base (default: the merge base with origin/main) and the version did not move;
--check fails instead. `version_ignore` in jarvis-build.json lists globs that do
not count (default for a repo-root plugin: .github/*, tests/*).

Stdlib only, Python 3.9+.
"""
import argparse
import fnmatch
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

GENERATED_NOTE = "Generated by tools/jarvis-build.py from {src}. Edit the source, then rebuild."
# Fields Claude Code ignores on plugin agents (docs: sub-agents, "plugin subagents").
PLUGIN_IGNORED = {"hooks", "mcpServers", "permissionMode", "initialPrompt"}
CLAUDE_AGENT_FIELDS = [
    "name", "description", "tools", "disallowedTools", "model", "permissionMode",
    "maxTurns", "skills", "mcpServers", "hooks", "memory", "background",
    "omitClaudeMd", "effort", "color", "initialPrompt",
]
BUILD_ONLY_FIELDS = {"rules", "standalone", "role_skill", "summary", "startup", "plugin_variant"}
SKILL_NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
DASHES = re.compile("[–—]")


class BuildError(Exception):
    pass


def parse_frontmatter(text, where):
    """Parse the small YAML subset our sources use: `key: value`, `key: [a, b]`, `- item` lists,
    and `key: {...}` with a one-line JSON object (for nested fields such as hooks)."""
    if not text.startswith("---\n"):
        raise BuildError(f"{where}: missing frontmatter")
    try:
        head, body = text[4:].split("\n---\n", 1)
    except ValueError:
        raise BuildError(f"{where}: unterminated frontmatter")
    data, key = {}, None
    for raw in head.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if raw.startswith("  - ") or raw.startswith("- "):
            if key is None or not isinstance(data.get(key), list):
                raise BuildError(f"{where}: list item without a list key: {raw!r}")
            data[key].append(unquote(raw.split("- ", 1)[1].strip()))
            continue
        if raw.startswith(" "):
            raise BuildError(f"{where}: nested YAML is not supported: {raw!r}")
        if ":" not in raw:
            raise BuildError(f"{where}: bad frontmatter line: {raw!r}")
        key, value = raw.split(":", 1)
        key, value = key.strip(), value.strip()
        if value == "":
            data[key] = []
        elif value.startswith("{"):
            try:
                data[key] = json.loads(value)
            except ValueError as e:
                raise BuildError(f"{where}: bad JSON object for '{key}': {e}")
        elif value.startswith("[") and value.endswith("]"):
            data[key] = [unquote(v.strip()) for v in value[1:-1].split(",") if v.strip()]
        elif value in ("true", "false"):
            data[key] = value == "true"
        else:
            data[key] = unquote(value)
    return data, body.lstrip("\n")


def unquote(value):
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return json.loads(value) if value[0] == '"' else value[1:-1]
    return value


def emit_frontmatter(fields):
    lines = ["---"]
    for key, value in fields.items():
        if isinstance(value, list):
            lines.append(f"{key}:")
            lines.extend(f"  - {json.dumps(v)}" for v in value)
        elif isinstance(value, bool):
            lines.append(f"{key}: {'true' if value else 'false'}")
        elif isinstance(value, dict):
            lines.append(f"{key}: {json.dumps(value)}")
        else:
            lines.append(f"{key}: {json.dumps(value)}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def dump_json(obj):
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


class Repo:
    def __init__(self, root):
        self.root = Path(root).resolve()
        self.config = json.loads((self.root / "jarvis-build.json").read_text())
        self.plugin_rel = self.config["plugin_dir"].strip("/") or "."
        self.plugin = (self.root / self.plugin_rel).resolve()
        self.manifest = json.loads((self.plugin / "jarvis-extension.json").read_text())
        self.peers_dir = self.root / self.config.get("peers_dir", "peers")
        self.outputs = {}
        self.errors = []

    # ---------- loading ----------
    @property
    def id(self):
        return self.manifest["id"]

    @property
    def is_core(self):
        return bool(self.manifest.get("core"))

    def peers(self):
        out = []
        if self.peers_dir.is_dir():
            for f in sorted(self.peers_dir.glob("*.json")):
                out.append(json.loads(f.read_text()))
        return out

    def core_manifest(self):
        if self.is_core:
            return self.manifest
        for p in self.peers():
            if p.get("core"):
                return p
        return None

    def disk_skills(self):
        skills = {}
        for f in sorted((self.plugin / "skills").glob("*/SKILL.md")):
            data, _ = parse_frontmatter(f.read_text(), str(f.relative_to(self.root)))
            skills[f.parent.name] = data
        return skills

    def agent_sources(self):
        agents = {}
        src = self.plugin / "agents-src"
        for f in sorted(src.glob("*.md")):
            rel = str(f.relative_to(self.root))
            data, body = parse_frontmatter(f.read_text(), rel)
            agents[data.get("name", f.stem)] = (data, body, rel)
        return agents

    def rule_text(self, name):
        f = self.plugin / "agents-src" / "rules" / f"{name}.md"
        if not f.is_file():
            raise BuildError(f"rule '{name}' not found at {f.relative_to(self.root)}")
        return f.read_text().strip()

    def skill_owner(self, skill):
        if skill in self.manifest.get("skills", []) or skill in self.generated_skill_names():
            return self.id
        core = self.core_manifest()
        if core and skill in core.get("skills", []) + ["extension-catalog"]:
            return core["id"]
        for p in self.peers():
            if skill in p.get("skills", []):
                return p["id"]
        raise BuildError(f"skill '{skill}' is not in this plugin, core, or a known peer")

    def generated_skill_names(self):
        names = {self.role_skill_name(n, d) for n, (d, _, _) in self.agent_sources().items()}
        names.add(self.router_name(self.manifest))
        return names

    @staticmethod
    def router_name(manifest):
        """The always-listed index skill of a plugin: core's catalog, else <id>-skills."""
        if manifest.get("core"):
            return "extension-catalog"
        return manifest.get("router") or f"{manifest['id']}-skills"

    def listing_config(self):
        c = self.config.get("listing", {})
        return {k: int(c.get(k, v)) for k, v in {
            "per_extension_chars": 1000, "manager_chars": 1500, "agent_chars": 2500,
            "catalog_line_max": 220, "listed_desc_max": 200, "skill_desc_max": 250}.items()}

    def listed_names(self):
        """Skills the model sees in its skill list: the router, every agent's preload skills,
        and the manifest's optional `listed`. Every other skill is hidden and reached by path
        through the router."""
        names = {self.router_name(self.manifest)} | set(self.manifest.get("listed", []))
        for data, _, _ in self.agent_sources().values():
            names |= set(data.get("skills", []))
        return names

    @staticmethod
    def role_skill_name(name, data):
        return data.get("role_skill") or f"role-{name}"

    def out(self, rel, text):
        self.outputs[rel] = text

    def prel(self, *parts):
        """Repo-relative path inside the plugin dir."""
        base = "" if self.plugin_rel == "." else self.plugin_rel + "/"
        return base + "/".join(parts)

    # ---------- generation ----------
    def build(self):
        agents = self.agent_sources()
        manifest_agents = {a["name"]: a for a in self.manifest.get("agents", [])}
        if set(agents) != set(manifest_agents):
            self.errors.append(
                f"manifest agents {sorted(manifest_agents)} != agents-src {sorted(agents)}")
        for name, (data, body, rel) in agents.items():
            self.build_agent(name, data, body, rel, manifest_agents.get(name, {}))
        if self.is_core:
            self.build_catalog()
        else:
            self.build_router()
        self.manage_hidden_skills()
        self.check_listing_budget()
        self.build_plugin_manifests()
        self.build_marketplaces()
        self.build_agents_md(agents, manifest_agents)

    def preload_names(self, data):
        return [f"{self.skill_owner(s)}:{s}" for s in data.get("skills", [])]

    def rules_block(self, data):
        rules = data.get("rules", [])
        if not rules:
            return ""
        parts = ["## Always-on rules", ""]
        for r in rules:
            text = self.rule_text(r)
            parts.append(re.sub(r"^# ", "### ", text, flags=re.M))
            parts.append("")
        return "\n".join(parts).rstrip() + "\n"

    def build_agent(self, name, data, body, rel, man):
        standalone = bool(data.get("standalone"))
        for field in data:
            if field not in CLAUDE_AGENT_FIELDS and field not in BUILD_ONLY_FIELDS:
                self.errors.append(f"{rel}: unknown agent field '{field}'")
        if not standalone:
            for field in PLUGIN_IGNORED & set(data):
                self.errors.append(
                    f"{rel}: '{field}' is ignored on plugin agents; drop it or set standalone: true")
        preload = self.preload_names(data)
        fields = {}
        for key in CLAUDE_AGENT_FIELDS:
            if key not in data:
                continue
            value = data[key]
            if key == "skills":
                value = preload
            if key == "initialPrompt" and value == "auto":
                extra = (" " + data["startup"].strip()) if data.get("startup") else ""
                value = ("Load these skills with the Skill tool: " + ", ".join(preload) + "."
                         + extra + " Then greet the user in one line.") if preload else None
            if value in (None, [], ""):
                continue
            fields[key] = value
        note = GENERATED_NOTE.format(src=rel)
        start = ""
        if preload:
            start = ("## Session start\n\n"
                     "These skills preload only when you run as a subagent. When you are the main "
                     "session (`--agent`), load any of them not already in your context with the "
                     "Skill tool before your first action: "
                     + ", ".join(f"`{p}`" for p in preload) + ".\n")
        router = self.router_name(self.manifest)
        start += ("\n" if start else "## Session start\n\n") + (
            f"A skill named in these instructions that is not in your skill list is hidden to save "
            f"the list's budget, not missing. Load `{self.id}:{router}` with the Skill tool (it is always "
            f"listed); it gives every skill of this plugin with its file path, and you read that file.\n")
        text = (emit_frontmatter(fields) + f"\n<!-- {note} -->\n\n" + body.rstrip() + "\n\n"
                + (start + "\n" if start else "") + self.rules_block(data))
        folder = "standalone" if standalone else "agents"
        self.out(self.prel(folder, f"{name}.md"), text.rstrip() + "\n")
        project_dir = self.config.get("project_agents_dir")
        if standalone and project_dir:
            self.out(f"{project_dir.strip('/')}/{name}.md", text.rstrip() + "\n")
        if standalone and data.get("plugin_variant"):
            self.build_plugin_variant(name, data, fields, body, note, start)
        self.build_role_skill(name, data, body, rel, man, preload)

    def build_plugin_variant(self, name, data, fields, body, note, start):
        """The same agent as a plugin agent (`<plugin>:<name>`), for a launch from a folder
        that has no project agent. Plugin agents ignore hooks and initialPrompt, so the
        launcher passes the hooks and the startup step moves into the body."""
        pfields = {k: v for k, v in fields.items() if k not in PLUGIN_IGNORED}
        pstart = start
        if data.get("startup"):
            pstart = (start.rstrip() + "\n\n" if start else "## Session start\n\n") + \
                "Before your first reply: " + data["startup"].strip() + "\n"
        text = (emit_frontmatter(pfields) + f"\n<!-- {note} -->\n\n" + body.rstrip() + "\n\n"
                + (pstart + "\n" if pstart else "") + self.rules_block(data))
        self.out(self.prel("agents", f"{name}.md"), text.rstrip() + "\n")

    def build_role_skill(self, name, data, body, rel, man, preload):
        skill = self.role_skill_name(name, data)
        summary = man.get("summary") or data.get("description", "")
        desc = (f"Act as the {name} role: {summary.rstrip('.')}. Load when your tool has no agent "
                f"files (Codex and others), or when a brief says load {skill}.")
        fields = {"name": skill, "description": desc}
        if skill not in self.listed_names():
            fields["disable-model-invocation"] = True
        load = ""
        tools = data.get("tools", "")
        if isinstance(tools, list):
            tools = ", ".join(tools)
        writers = ("Edit", "Write", "MultiEdit", "NotebookEdit", "Bash")
        if tools and not any(w in tools for w in writers):
            load += ("## Read-only\n\nThis role is read-only: read and search, never edit, write, "
                     "commit, or run a command that changes files or state, apart from the status and "
                     "report files your brief names. Claude Code enforces it "
                     f"with the agent's tools ({tools}). Codex and other tools cannot, so follow it "
                     "yourself. Outside a fleet, `codex --sandbox read-only` enforces it; a fleet "
                     "worker keeps the normal sandbox because it must write its status and report "
                     "files.\n\n")
        if preload:
            bare = [p.split(":", 1)[1] for p in preload]
            load = ("## Load first\n\nLoad these skills before your first action: "
                    + ", ".join(f"`{b}`" for b in bare) + ".\n\n") + load
        text = (emit_frontmatter(fields)
                + f"\n<!-- {GENERATED_NOTE.format(src=rel)} -->\n\n"
                + f"# Role: {name}\n\n" + load + body.rstrip() + "\n\n" + self.rules_block(data))
        self.out(self.prel("skills", skill, "SKILL.md"), text.rstrip() + "\n")

    def catalog_agent_rows(self):
        """One row per agent of every known extension: what it does and when to dispatch it."""
        rows = []
        for ext in [p for p in self.peers() if not p.get("core")]:
            for a in ext.get("agents", []):
                line = f"{a['summary'].rstrip('.')}. Dispatch when: {a['dispatch_when'].rstrip('.')}."
                rows.append((ext, a, line[0].upper() + line[1:]))
        return rows

    def build_catalog(self):
        """Level 1 of skill routing: the manager sees agents, never extension skills."""
        mk = self.config["marketplace"]["name"]
        repo = self.manifest.get("repo", "")
        lines = [
            emit_frontmatter({
                "name": "extension-catalog",
                "description": ("Lists every known Jarvis agent, what it does and when to dispatch it, "
                                "how to launch it, and the core skills. Load before routing or "
                                "dispatching work to a worker."),
            }),
            f"<!-- {GENERATED_NOTE.format(src='jarvis-extension.json manifests')} -->",
            "",
            "# Extension catalog",
            "",
            "Pick the agent whose line matches the work and dispatch it. You see agents, not their "
            "skills: each worker launches with core plus only its own extension and finds that "
            "extension's skills through the extension's router.",
            "",
            "## Agents",
            "",
            "| Agent | What it does, when to dispatch | Claude Code |",
            "|---|---|---|",
        ]
        for ext, a, line in self.catalog_agent_rows():
            lines.append(f"| `{ext['id']}:{a['name']}` | {line} | `claude --agent {ext['id']}:{a['name']}` |")
        lines += [
            "",
            "From a home, launch with `bin/fm-spawn.sh ... --agent <plugin>:<agent>`: the spawn turns on "
            "core and that one extension for the worker and turns every other known extension off. By "
            "hand: `claude --agent <plugin>:<agent> --settings \"$(bin/jarvis-plugins-for.sh "
            "<plugin>)\"`. Codex has no agent files and no per-launch plugin switch: start the worker "
            "with a brief whose first line is \"Load `$role-<agent>` first\" (docs/jarvis-plugins.md, "
            "\"Skill listing budget\"). Other tools: tell the worker to load `role-<agent>`.",
            "",
            "## Installed or not",
            "",
            "Check before routing. Claude Code: `claude plugin list` shows `<plugin>@" + mk + "` or "
            "`<plugin>@<plugin>` (installed from its own marketplace); either counts, enabled or not. "
            "Codex: its plugin list, under either marketplace. In a home, `bin/jarvis-setup.sh status` "
            "checks the current tool.",
            "",
            "When the work needs an agent whose extension is not installed, ask in one line, for "
            "example \"That needs the coding agent from GeorgeCodingAgent. Install it?\" On yes, run "
            "its install line yourself, then dispatch; the manager needs no restart. Never install "
            "without that yes.",
            "",
            "| Extension | Install (Claude Code) | Install (Codex) |",
            "|---|---|---|",
        ]
        for ext in [p for p in self.peers() if not p.get("core")]:
            lines.append(f"| {ext['name']} | `claude plugin install {ext['id']}@{mk}` | "
                         f"`codex plugin add {ext['id']}@{mk}` (after `codex plugin marketplace add {repo}`) |")
        lines += [
            "",
            "## Core skills",
            "",
            self.ROUTER_HOWTO,
            "",
            *self.router_table(),
        ]
        self.out(self.prel("skills", "extension-catalog", "SKILL.md"), "\n".join(lines).rstrip() + "\n")

    @staticmethod
    def first_sentence(desc, limit=220):
        desc = " ".join(str(desc).split())
        m = re.match(r"(.+?[.!?])(\s|$)", desc)
        out = m.group(1) if m else desc
        return out if len(out) <= limit else out[:limit - 3].rstrip() + "..."

    def skill_rows(self):
        """(name, one-line summary) for every hand skill and generated role skill of this plugin."""
        rows = []
        disk = self.disk_skills()
        for name in self.manifest.get("skills", []):
            rows.append((name, self.first_sentence(disk.get(name, {}).get("description", ""))))
        for agent, (data, _, _) in sorted(self.agent_sources().items()):
            rows.append((self.role_skill_name(agent, data), f"Act as the `{agent}` role (for tools without agent files)."))
        return rows

    def router_table(self):
        listed = self.listed_names()
        lines = ["| Skill | What it is for | Listed |", "|---|---|---|"]
        for name, summary in self.skill_rows():
            lines.append(f"| [`{name}`](../{name}/SKILL.md) | {summary} | {'yes' if name in listed else 'no'} |")
        return lines

    ROUTER_HOWTO = ("To use a skill, load it with the Skill tool when it is in your skill list, else "
                    "read its file: `../<skill>/SKILL.md`, relative to this skill's folder (its base "
                    "directory). Follow that file as if it had been invoked. Skills marked \"no\" are "
                    "hidden from the skill list to keep the list inside its budget; they are not "
                    "deprecated.")

    def build_router(self):
        name = self.router_name(self.manifest)
        m = self.manifest
        desc = (f"Index of every {m['name']} skill with a one-line summary and its file. Load it to "
                f"find the right skill for plan, build, test, review or ship work, then read that skill.")
        lines = [emit_frontmatter({"name": name, "description": desc}),
                 f"<!-- {GENERATED_NOTE.format(src='jarvis-extension.json')} -->", "",
                 f"# {m['name']} skills", "", self.ROUTER_HOWTO, ""]
        lines += self.router_table()
        self.out(self.prel("skills", name, "SKILL.md"), "\n".join(lines).rstrip() + "\n")

    def manage_hidden_skills(self):
        """Hidden hand skills carry `disable-model-invocation: true` (Claude Code drops them from
        the listing); listed ones must not. The build writes the field into the source."""
        listed = self.listed_names()
        for name in self.manifest.get("skills", []):
            f = self.plugin / "skills" / name / "SKILL.md"
            if not f.is_file():
                continue
            text = f.read_text()
            head, body = text[4:].split("\n---\n", 1)
            has = re.search(r"(?m)^disable-model-invocation:\s*true\s*$", head) is not None
            if name in listed and has:
                head = re.sub(r"(?m)^disable-model-invocation:.*\n?", "", head).rstrip("\n")
            elif name not in listed and not has:
                head = re.sub(r"(?m)^disable-model-invocation:.*\n?", "", head).rstrip("\n")
                head += "\ndisable-model-invocation: true"
            else:
                continue
            self.out(str(f.relative_to(self.root)), "---\n" + head + "\n---\n" + body)

    def listed_descriptions(self):
        """name -> description for every listed skill, from outputs or disk."""
        out = {}
        disk = self.disk_skills()
        for name in sorted(self.listed_names()):
            rel = self.prel("skills", name, "SKILL.md")
            if rel in self.outputs:
                data, _ = parse_frontmatter(self.outputs[rel], rel)
            else:
                data = disk.get(name, {})
            out[name] = str(data.get("description", ""))
        return out

    def check_listing_budget(self):
        """Budgets per launch shape, never one combined total. An extension checks its own
        listed share. Core checks the manager shape (core alone: the manager sees agents in the
        catalog, not extension skills) and every known agent's shape (core plus that agent's own
        extension at its capped share), so adding extensions never fails the check."""
        c = self.listing_config()
        per_ext = c["per_extension_chars"]
        known = set(self.manifest.get("skills", [])) | self.generated_skill_names()
        for name in sorted(self.listed_names()):
            if name not in known:
                self.errors.append(f"listed skill '{name}' is not a skill of this plugin")
        used = 0
        for name, desc in self.listed_descriptions().items():
            if len(desc) > c["listed_desc_max"]:
                self.errors.append(f"listed skill '{name}': description is {len(desc)} chars (listed max {c['listed_desc_max']})")
            used += len(name) + len(desc) + 4
        for name, data in self.disk_skills().items():
            d = str(data.get("description", ""))
            if name in known and len(d) > c["skill_desc_max"]:
                self.errors.append(f"skill '{name}': description is {len(d)} chars (max {c['skill_desc_max']})")
        budget = int(self.manifest.get("listing_budget", per_ext))
        if budget > per_ext:
            self.errors.append(f"listing_budget {budget} is over the per-extension cap {per_ext}")
        self.listing_used = used
        self.shapes = {}
        if not self.is_core:
            if used > budget:
                self.errors.append(f"listed skills use {used} chars, over this plugin's listing budget {budget}; "
                                   "hide a skill behind the router or shorten a description")
            return
        if used > c["manager_chars"]:
            self.errors.append(f"manager launch shape lists {used} chars, over its budget {c['manager_chars']}")
        self.shapes["manager"] = used
        for ext, a, line in self.catalog_agent_rows():
            if len(line) > c["catalog_line_max"]:
                self.errors.append(f"catalog line for {ext['id']}:{a['name']} is {len(line)} chars (max {c['catalog_line_max']})")
            share = min(int(ext.get("listing_budget", per_ext)), per_ext)
            shape = used + share
            self.shapes[f"{ext['id']}:{a['name']}"] = shape
            if shape > c["agent_chars"]:
                self.errors.append(f"launch shape of {ext['id']}:{a['name']} (core {used} + extension {share}) "
                                   f"is over its budget {c['agent_chars']}")

