#!/usr/bin/env python3
"""Build the per-tool adapters of a Jarvis plugin repo from its sources.

Sources (hand-edited):
  jarvis-build.json                      repo config: plugin dir, marketplace, peers
  <plugin>/jarvis-extension.json         the manifest: id, agents, skills, relies_on_core
  <plugin>/agents-src/<agent>.md         one source per agent (frontmatter plus body)
  <plugin>/agents-src/rules/<rule>.md    must-follow rules, inlined into agents at build
  <plugin>/skills/<skill>/SKILL.md       skills
  <peers_dir>/<id>.json                  vendored manifests of known peer plugins

Outputs (generated, never hand-edit):
  <plugin>/agents/<agent>.md             Claude Code plugin agents
  <plugin>/standalone/<agent>.md         agents to copy into ~/.claude/agents/
  <plugin>/skills/role-*/SKILL.md        role skills for tools without agent files
  <plugin>/skills/extension-catalog/     core only: every known extension
  <plugin>/.claude-plugin/plugin.json    Claude plugin manifest
  <plugin>/.codex-plugin/plugin.json     Codex plugin manifest
  <plugin>/AGENTS.md, <plugin>/CLAUDE.md always-on file, CLAUDE.md imports it
  .claude-plugin/marketplace.json        Claude marketplace
  .agents/plugins/marketplace.json       Codex marketplace

Usage:
  python3 tools/jarvis-build.py            write every output
  python3 tools/jarvis-build.py --check    fail if any output is stale or a check fails (CI)
  python3 tools/jarvis-build.py --fetch    refresh vendored peer manifests from GitHub

Stdlib only, Python 3.9+.
"""
import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

GENERATED_NOTE = "Generated by tools/jarvis-build.py from {src}. Edit the source, then rebuild."
# Fields Claude Code ignores on plugin agents (docs: sub-agents, "plugin subagents").
PLUGIN_IGNORED = {"hooks", "mcpServers", "permissionMode", "initialPrompt"}
CLAUDE_AGENT_FIELDS = [
    "name", "description", "tools", "disallowedTools", "model", "permissionMode",
    "maxTurns", "skills", "mcpServers", "hooks", "memory", "background",
    "omitClaudeMd", "effort", "color", "initialPrompt",
]
BUILD_ONLY_FIELDS = {"rules", "standalone", "role_skill", "summary"}
SKILL_NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
DASHES = re.compile("[–—]")


class BuildError(Exception):
    pass


def parse_frontmatter(text, where):
    """Parse the small YAML subset our sources use: `key: value`, `key: [a, b]`, `- item` lists."""
    if not text.startswith("---\n"):
        raise BuildError(f"{where}: missing frontmatter")
    try:
        head, body = text[4:].split("\n---\n", 1)
    except ValueError:
        raise BuildError(f"{where}: unterminated frontmatter")
    data, key = {}, None
    for raw in head.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if raw.startswith("  - ") or raw.startswith("- "):
            if key is None or not isinstance(data.get(key), list):
                raise BuildError(f"{where}: list item without a list key: {raw!r}")
            data[key].append(unquote(raw.split("- ", 1)[1].strip()))
            continue
        if raw.startswith(" "):
            raise BuildError(f"{where}: nested YAML is not supported: {raw!r}")
        if ":" not in raw:
            raise BuildError(f"{where}: bad frontmatter line: {raw!r}")
        key, value = raw.split(":", 1)
        key, value = key.strip(), value.strip()
        if value == "":
            data[key] = []
        elif value.startswith("[") and value.endswith("]"):
            data[key] = [unquote(v.strip()) for v in value[1:-1].split(",") if v.strip()]
        elif value in ("true", "false"):
            data[key] = value == "true"
        else:
            data[key] = unquote(value)
    return data, body.lstrip("\n")


def unquote(value):
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return json.loads(value) if value[0] == '"' else value[1:-1]
    return value


def emit_frontmatter(fields):
    lines = ["---"]
    for key, value in fields.items():
        if isinstance(value, list):
            lines.append(f"{key}:")
            lines.extend(f"  - {json.dumps(v)}" for v in value)
        elif isinstance(value, bool):
            lines.append(f"{key}: {'true' if value else 'false'}")
        else:
            lines.append(f"{key}: {json.dumps(value)}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def dump_json(obj):
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


class Repo:
    def __init__(self, root):
        self.root = Path(root).resolve()
        self.config = json.loads((self.root / "jarvis-build.json").read_text())
        self.plugin_rel = self.config["plugin_dir"].strip("/") or "."
        self.plugin = (self.root / self.plugin_rel).resolve()
        self.manifest = json.loads((self.plugin / "jarvis-extension.json").read_text())
        self.peers_dir = self.root / self.config.get("peers_dir", "peers")
        self.outputs = {}
        self.errors = []

    # ---------- loading ----------
    @property
    def id(self):
        return self.manifest["id"]

    @property
    def is_core(self):
        return bool(self.manifest.get("core"))

    def peers(self):
        out = []
        if self.peers_dir.is_dir():
            for f in sorted(self.peers_dir.glob("*.json")):
                out.append(json.loads(f.read_text()))
        return out

    def core_manifest(self):
        if self.is_core:
            return self.manifest
        for p in self.peers():
            if p.get("core"):
                return p
        return None

    def disk_skills(self):
        skills = {}
        for f in sorted((self.plugin / "skills").glob("*/SKILL.md")):
            data, _ = parse_frontmatter(f.read_text(), str(f.relative_to(self.root)))
            skills[f.parent.name] = data
        return skills

    def agent_sources(self):
        agents = {}
        src = self.plugin / "agents-src"
        for f in sorted(src.glob("*.md")):
            rel = str(f.relative_to(self.root))
            data, body = parse_frontmatter(f.read_text(), rel)
            agents[data.get("name", f.stem)] = (data, body, rel)
        return agents

    def rule_text(self, name):
        f = self.plugin / "agents-src" / "rules" / f"{name}.md"
        if not f.is_file():
            raise BuildError(f"rule '{name}' not found at {f.relative_to(self.root)}")
        return f.read_text().strip()

    def skill_owner(self, skill):
        if skill in self.manifest.get("skills", []) or skill in self.generated_skill_names():
            return self.id
        core = self.core_manifest()
        if core and skill in core.get("skills", []) + ["extension-catalog"]:
            return core["id"]
        for p in self.peers():
            if skill in p.get("skills", []):
                return p["id"]
        raise BuildError(f"skill '{skill}' is not in this plugin, core, or a known peer")

    def generated_skill_names(self):
        names = {self.role_skill_name(n, d) for n, (d, _, _) in self.agent_sources().items()}
        if self.is_core:
            names.add("extension-catalog")
        return names

    @staticmethod
    def role_skill_name(name, data):
        return data.get("role_skill") or f"role-{name}"

    def out(self, rel, text):
        self.outputs[rel] = text

    def prel(self, *parts):
        """Repo-relative path inside the plugin dir."""
        base = "" if self.plugin_rel == "." else self.plugin_rel + "/"
        return base + "/".join(parts)

    # ---------- generation ----------
    def build(self):
        agents = self.agent_sources()
        manifest_agents = {a["name"]: a for a in self.manifest.get("agents", [])}
        if set(agents) != set(manifest_agents):
            self.errors.append(
                f"manifest agents {sorted(manifest_agents)} != agents-src {sorted(agents)}")
        for name, (data, body, rel) in agents.items():
            self.build_agent(name, data, body, rel, manifest_agents.get(name, {}))
        if self.is_core:
            self.build_catalog()
        self.build_plugin_manifests()
        self.build_marketplaces()
        self.build_agents_md(agents, manifest_agents)

    def preload_names(self, data):
        return [f"{self.skill_owner(s)}:{s}" for s in data.get("skills", [])]

    def rules_block(self, data):
        rules = data.get("rules", [])
        if not rules:
            return ""
        parts = ["## Always-on rules", ""]
        for r in rules:
            text = self.rule_text(r)
            parts.append(re.sub(r"^# ", "### ", text, flags=re.M))
            parts.append("")
        return "\n".join(parts).rstrip() + "\n"

    def build_agent(self, name, data, body, rel, man):
        standalone = bool(data.get("standalone"))
        for field in data:
            if field not in CLAUDE_AGENT_FIELDS and field not in BUILD_ONLY_FIELDS:
                self.errors.append(f"{rel}: unknown agent field '{field}'")
        if not standalone:
            for field in PLUGIN_IGNORED & set(data):
                self.errors.append(
                    f"{rel}: '{field}' is ignored on plugin agents; drop it or set standalone: true")
        preload = self.preload_names(data)
        fields = {}
        for key in CLAUDE_AGENT_FIELDS:
            if key not in data:
                continue
            value = data[key]
            if key == "skills":
                value = preload
            if key == "initialPrompt" and value == "auto":
                value = ("Load these skills with the Skill tool: " + ", ".join(preload)
                         + ". Then greet the user in one line.") if preload else None
            if value in (None, [], ""):
                continue
            fields[key] = value
        note = GENERATED_NOTE.format(src=rel)
        start = ""
        if preload:
            start = ("## Session start\n\n"
                     "These skills preload only when you run as a subagent. When you are the main "
                     "session (`--agent`), load any of them not already in your context with the "
                     "Skill tool before your first action: "
                     + ", ".join(f"`{p}`" for p in preload) + ".\n")
        text = (emit_frontmatter(fields) + f"\n<!-- {note} -->\n\n" + body.rstrip() + "\n\n"
                + (start + "\n" if start else "") + self.rules_block(data))
        folder = "standalone" if standalone else "agents"
        self.out(self.prel(folder, f"{name}.md"), text.rstrip() + "\n")
        self.build_role_skill(name, data, body, rel, man, preload)

    def build_role_skill(self, name, data, body, rel, man, preload):
        skill = self.role_skill_name(name, data)
        summary = man.get("summary") or data.get("description", "")
        desc = (f"Act as the {name} role: {summary.rstrip('.')}. Load when your tool has no agent "
                f"files (Codex and others), or when a brief says load {skill}.")
        fields = {"name": skill, "description": desc}
        load = ""
        if preload:
            bare = [p.split(":", 1)[1] for p in preload]
            load = ("## Load first\n\nLoad these skills before your first action: "
                    + ", ".join(f"`{b}`" for b in bare) + ".\n\n")
        text = (emit_frontmatter(fields)
                + f"\n<!-- {GENERATED_NOTE.format(src=rel)} -->\n\n"
                + f"# Role: {name}\n\n" + load + body.rstrip() + "\n\n" + self.rules_block(data))
        self.out(self.prel("skills", skill, "SKILL.md"), text.rstrip() + "\n")

    def build_catalog(self):
        exts = [self.manifest] + [p for p in self.peers() if not p.get("core")]
        mk = self.config["marketplace"]["name"]
        lines = [
            emit_frontmatter({
                "name": "extension-catalog",
                "description": ("Lists every known Jarvis extension: its agents, when to dispatch "
                                "each, its skills, and how to launch it in Claude Code or another "
                                "tool. Load before routing or dispatching work to a worker."),
            }),
            f"<!-- {GENERATED_NOTE.format(src='jarvis-extension.json manifests')} -->",
            "",
            "# Extension catalog",
            "",
            "Pick the extension and agent whose `dispatch when` matches the work. Launch the worker "
            "with the line shown. An extension that is not installed is listed with its install line.",
            "",
            "Claude Code launch shape: `claude --agent <plugin>:<agent> --settings "
            "'{\"enabledPlugins\":{\"<plugin>@" + mk + "\":true}}'` (the `--settings` part turns the "
            "extension on for that worker only). Other tools: tell the worker to load `role-<agent>`.",
            "",
        ]
        for ext in exts:
            lines += [f"## {ext['name']} (`{ext['id']}`)", "", ext.get("description", ""), ""]
            if not ext.get("core"):
                lines += [f"Install: `claude plugin install {ext['id']}@{mk}`", ""]
            lines += ["| Agent | Dispatch when | Claude Code | Other tools |", "|---|---|---|---|"]
            own = self.agent_sources() if ext is self.manifest else {}
            for a in ext.get("agents", []):
                data = own.get(a["name"], ({}, "", ""))[0]
                launch = f"`claude --agent {ext['id']}:{a['name']}`"
                if data.get("standalone"):
                    launch = f"`claude --agent {a['name']}` (standalone file, see the install docs)"
                role = self.role_skill_name(a["name"], data)
                lines.append(f"| `{a['name']}` | {a['dispatch_when']} | {launch} | load `{role}` |")
            lines += ["", "Skills: " + ", ".join(f"`{s}`" for s in ext.get("skills", [])), ""]
            if ext.get("relies_on_core"):
                lines += ["Relies on core: " + ", ".join(f"`{s}`" for s in ext["relies_on_core"]), ""]
        self.out(self.prel("skills", "extension-catalog", "SKILL.md"), "\n".join(lines).rstrip() + "\n")

    def build_plugin_manifests(self):
        m = self.manifest
        author = m.get("author", {"name": self.config["marketplace"]["owner"]["name"]})
        home = f"https://github.com/{m['repo']}"
        claude = {
            "name": m["id"], "version": m["version"], "description": m["description"],
            "author": author, "homepage": home, "repository": home, "license": m.get("license", "MIT"),
            "keywords": m.get("keywords", []),
        }
        self.out(self.prel(".claude-plugin", "plugin.json"), dump_json(claude))
        codex = {
            "name": m["id"], "version": m["version"], "description": m["description"],
            "author": author, "homepage": home, "repository": home, "license": m.get("license", "MIT"),
            "skills": "./skills/",
            "interface": {
                "displayName": m["name"],
                "shortDescription": m["description"],
                "developerName": author["name"],
                "category": "Productivity",
                "capabilities": ["Interactive", "Read", "Write"],
            },
        }
        self.out(self.prel(".codex-plugin", "plugin.json"), dump_json(codex))

    def market_entries(self):
        """(manifest, claude_source, codex_source) for every plugin this marketplace lists."""
        own_path = "./" if self.plugin_rel == "." else f"./{self.plugin_rel}"
        entries = [(self.manifest, own_path, {"source": "local", "path": own_path})]
        for p in self.peers():
            if p.get("core"):
                path = p.get("plugin_path", ".")
                if path in (".", ""):
                    cs = {"source": "github", "repo": p["repo"]}
                    xs = {"source": "url", "url": f"https://github.com/{p['repo']}.git"}
                else:
                    cs = {"source": "git-subdir", "url": p["repo"], "path": path}
                    xs = {"source": "git-subdir", "url": f"https://github.com/{p['repo']}.git", "path": path}
            else:
                cs = {"source": "github", "repo": p["repo"]}
                xs = {"source": "url", "url": f"https://github.com/{p['repo']}.git"}
            entries.append((p, cs, xs))
        return entries

    def build_marketplaces(self):
        mk = self.config["marketplace"]
        claude = {
            "$schema": "https://json.schemastore.org/claude-code-marketplace.json",
            "name": mk["name"], "description": mk["description"], "owner": mk["owner"],
            "plugins": [],
        }
        codex = {"name": mk["name"], "interface": {"displayName": mk.get("display_name", mk["name"])},
                 "plugins": []}
        for m, cs, xs in self.market_entries():
            claude["plugins"].append({
                "name": m["id"], "version": m["version"], "source": cs,
                "description": m["description"], "homepage": f"https://github.com/{m['repo']}",
                "license": m.get("license", "MIT"),
            })
            codex["plugins"].append({
                "name": m["id"], "version": m["version"], "description": m["description"],
                "source": xs, "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                "category": "Productivity",
            })
        self.out(".claude-plugin/marketplace.json", dump_json(claude))
        self.out(".agents/plugins/marketplace.json", dump_json(codex))

    def build_agents_md(self, agents, manifest_agents):
        m = self.manifest
        mk = self.config["marketplace"]["name"]
        lines = [
            f"<!-- {GENERATED_NOTE.format(src='jarvis-extension.json and agents-src/')} -->",
            "",
            f"# {m['name']}",
            "",
            m["description"],
            "",
            "## Roles",
            "",
            "| Role | When | Claude Code | Other tools |",
            "|---|---|---|---|",
        ]
        for name, (data, _, _) in agents.items():
            man = manifest_agents.get(name, {})
            launch = (f"`claude --agent {name}` (copy `standalone/{name}.md` to `~/.claude/agents/`)"
                      if data.get("standalone") else f"`claude --agent {m['id']}:{name}`")
            lines.append(f"| `{name}` | {man.get('dispatch_when', '')} | {launch} | "
                         f"load skill `{self.role_skill_name(name, data)}` |")
        lines += [
            "",
            "Each role's must-follow rules are inside its agent file (Claude Code) and its role "
            "skill (other tools). This file is not loaded by Claude Code from inside a plugin.",
            "",
            "## Skills",
            "",
            ", ".join(f"`{s}`" for s in m.get("skills", [])),
            "",
        ]
        if m.get("relies_on_core"):
            lines += ["Relies on core (install the core plugin first): "
                      + ", ".join(f"`{s}`" for s in m["relies_on_core"]), ""]
        lines += [
            "## Editing",
            "",
            "- Edit `jarvis-extension.json`, `agents-src/` and `skills/`. Never edit generated files "
            "(`agents/`, `standalone/`, `skills/role-*`, `skills/extension-catalog`, plugin and "
            "marketplace JSON, this file).",
            "- Rebuild with `python3 tools/jarvis-build.py`; CI runs it with `--check`.",
            f"- Install for Claude Code: `claude plugin marketplace add {m['repo']}`, then "
            f"`claude plugin install {m['id']}@{mk}`.",
            "",
        ]
        self.out(self.prel("AGENTS.md"), "\n".join(lines))
        self.out(self.prel("CLAUDE.md"), "@AGENTS.md\n")

    # ---------- checks ----------
    def check_sources(self):
        disk = self.disk_skills()
        generated = self.generated_skill_names()
        declared = set(self.manifest.get("skills", []))
        hand = set(disk) - generated
        if declared != hand:
            if declared - hand:
                self.errors.append(f"manifest lists skills not on disk: {sorted(declared - hand)}")
            if hand - declared:
                self.errors.append(f"skills on disk missing from manifest: {sorted(hand - declared)}")
        for name, data in disk.items():
            if name in generated:
                continue
            rel = self.prel("skills", name, "SKILL.md")
            if data.get("name") != name:
                self.errors.append(f"{rel}: frontmatter name '{data.get('name')}' != folder '{name}'")
            if not SKILL_NAME.match(name):
                self.errors.append(f"{rel}: skill name must be kebab-case")
            desc = data.get("description", "")
            if not isinstance(desc, str) or not desc.strip():
                self.errors.append(f"{rel}: missing description")
            elif len(desc) > 1024:
                self.errors.append(f"{rel}: description is {len(desc)} chars (max 1024)")
        # One owner per skill name across this plugin and every known peer.
        seen = {}
        for m in [self.manifest] + self.peers():
            if m is self.manifest:
                names = list(m.get("skills", [])) + sorted(self.generated_skill_names())
            else:
                names = list(m.get("skills", [])) + [f"role-{a['name']}" for a in m.get("agents", [])]
                if m.get("core"):
                    names += ["extension-catalog", "role-jarvis"]
            for s in names:
                if s in seen and seen[s] != m["id"]:
                    self.errors.append(f"duplicate skill name '{s}' in {seen[s]} and {m['id']}")
                seen.setdefault(s, m["id"])
        core = self.core_manifest()
        if core and not self.is_core:
            missing = set(self.manifest.get("relies_on_core", [])) - set(core.get("skills", []))
            if missing:
                self.errors.append(f"relies_on_core names skills core does not ship: {sorted(missing)}")
        for f in sorted((self.plugin / "agents-src").rglob("*.md")):
            for i, line in enumerate(f.read_text().splitlines(), 1):
                if DASHES.search(line):
                    self.errors.append(f"{f.relative_to(self.root)}:{i}: em or en dash in agent source")

    def stale(self):
        stale = []
        for rel, text in sorted(self.outputs.items()):
            f = self.root / rel
            if not f.is_file() or f.read_text() != text:
                stale.append(rel)
        for folder in ("agents", "standalone"):
            d = self.plugin / folder
            if d.is_dir():
                for f in d.glob("*.md"):
                    rel = str(f.relative_to(self.root))
                    if rel not in self.outputs:
                        stale.append(rel + " (orphan)")
        for f in (self.plugin / "skills").glob("role-*/SKILL.md"):
            rel = str(f.relative_to(self.root))
            if rel not in self.outputs:
                stale.append(rel + " (orphan)")
        return stale

    def write(self):
        for rel, text in self.outputs.items():
            f = self.root / rel
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(text)

    def fetch(self):
        self.peers_dir.mkdir(parents=True, exist_ok=True)
        for peer in self.config.get("peers", []):
            url = (f"https://raw.githubusercontent.com/{peer['repo']}/{peer.get('ref', 'main')}/"
                   f"{peer['manifest_path']}")
            with urllib.request.urlopen(url, timeout=30) as resp:
                data = json.loads(resp.read().decode())
            target = self.peers_dir / f"{data['id']}.json"
            target.write_text(dump_json(data))
            print(f"fetched {url} -> {target.relative_to(self.root)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=".", help="repo root (default: cwd)")
    ap.add_argument("--check", action="store_true", help="fail on stale outputs or failed checks")
    ap.add_argument("--fetch", action="store_true", help="refresh vendored peer manifests, then build")
    args = ap.parse_args()
    repo = Repo(args.root)
    try:
        if args.fetch:
            repo.fetch()
        repo.check_sources()
        repo.build()
    except BuildError as e:
        print(f"jarvis-build: {e}", file=sys.stderr)
        return 2
    if repo.errors:
        for e in repo.errors:
            print(f"jarvis-build: {e}", file=sys.stderr)
        return 1
    if args.check:
        stale = repo.stale()
        if stale:
            print("jarvis-build: stale outputs (run python3 tools/jarvis-build.py):", file=sys.stderr)
            for s in stale:
                print(f"  {s}", file=sys.stderr)
            return 1
        print(f"jarvis-build: {len(repo.outputs)} outputs up to date, checks passed")
        return 0
    repo.write()
    print(f"jarvis-build: wrote {len(repo.outputs)} outputs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
